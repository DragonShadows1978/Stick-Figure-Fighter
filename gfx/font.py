SMALL_CAPS = 0.76  # lowercase height relative to caps


def glyph_strokes(ch: str) -> Tuple[float, List[Stroke], float]:
    """(advance, strokes, scale) for a character; lowercase -> scaled caps on the baseline."""
    scale = 1.0
    if ch.islower() and ch.upper() in GLYPHS:
        ch = ch.upper()
        scale = SMALL_CAPS
    adv, strokes = GLYPHS.get(ch, GLYPHS["?"])
    if scale != 1.0:
        strokes = [[(x * scale, 10 - (10 - y) * scale) for x, y in s] for s in strokes]
        adv *= scale
    return adv, strokes, scale
