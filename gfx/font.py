"""
Stroke font: every glyph is a set of polylines on a grid where y=0 is the
cap line and y=10 the baseline. Rendering turns the strokes into distance
fields, so one definition yields crisp neon tubes, wobbly ink lettering, or
thin elegant caps depending on weight/jitter.

Lowercase letters render as small caps.
"""
import math
from typing import Dict, List, Sequence, Tuple

Pt = Tuple[float, float]
Stroke = List[Pt]


def arc(cx, cy, rx, ry, a0, a1, n=0) -> Stroke:
    """Points along an elliptical arc; angles in degrees, 0 = right, 90 = down."""
    n = n or max(6, int(abs(a1 - a0) / 12))
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def ell(cx, cy, rx, ry) -> Stroke:
    return arc(cx, cy, rx, ry, 0, 360, 32)


def dot(x, y) -> Stroke:
    return [(x, y), (x, y)]


